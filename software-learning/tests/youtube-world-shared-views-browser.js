// Run with agent-browser eval --stdin in a fresh chapter 14 live-world browser session.
(() => {
    const results = [];
    const check = (ok, name) => { if (!ok) throw new Error(name); results.push(name); };
    const click = selector => document.querySelector(selector).click();
    const hook = window.__worldWorkbench, world = hook.world;
    if (!hook.paused) click('[data-action="pause"]');
    Object.assign(world.options, {autoFaults: false, arrivals: false, autoRepair: false});
    const region = world.users[0].region;
    document.querySelector('#yw-group-region').value = region;
    document.querySelector('#yw-add-count').value = '5';
    const before = world.users.length;
    click('[data-action="add-users"]');
    world.step(.1); hook.paint();
    const request = world.requests.find(r => r.userId === 1);
    const snapshot = () => JSON.stringify([world.time, world.randomState, world.users, world.machines, world.requests]);
    const state = snapshot();
    click('[data-world-view="architecture"]');
    check(hook.world === world && snapshot() === state, 'switch preserves exact world identity, requests, RNG and clock');
    check(world.users.length === before + 5, 'five added viewers survive view switch');
    check(document.querySelector(`[data-graph-count="${region}"]`).textContent.includes(`目前 ${before + 5} 人`), 'architecture population comes from same users');
    check(document.querySelectorAll('[data-graph-user]').length === world.users.length, 'small population shows every real viewer');
    check(!document.querySelector('.yw-diagram').hidden && document.querySelector('.yw-topology').hidden, 'architecture is the active projection');
    const machine = world.machines.find(m => m.kind === 'stream' && m.region === region);
    const g = document.querySelector(`[data-graph-machine="${machine.id}"]`);
    g.dispatchEvent(new MouseEvent('click', {bubbles: true}));
    click('[data-action="toggle-machine"]');
    check(!machine.up && g.classList.contains('down'), 'diagram selects and shuts down the actual machine');
    const afterFailure = snapshot();
    click('[data-world-view="people"]');
    check(snapshot() === afterFailure, 'switching back does not repair or restart anything');
    check(document.querySelector(`[data-machine="${machine.id}"]`).classList.contains('is-down'), 'same machine is down in people view');
    check(document.querySelector(`[data-region-count="${region}"]`).textContent.startsWith(`${before + 5} 人`), 'both views show same regional population');
    const cdnToggle = document.querySelector('[data-option="cdn"]');
    cdnToggle.checked = false; cdnToggle.dispatchEvent(new Event('change', {bubbles: true}));
    click('[data-world-view="architecture"]');
    const cdn = world.machines.find(m => m.kind === 'cdn' && m.region === region);
    check(document.querySelector(`[data-graph-machine="${cdn.id}"]`).classList.contains('disabled'), 'CDN disabled state is shared');
    check(world.requests.includes(request), 'request objects survive machine operation and view changes');
    check(document.querySelector('.yw-diagram-status').textContent.includes(request.id), 'diagram follows the same current request ID');
    g.dispatchEvent(new MouseEvent('click', {bubbles: true}));
    const machinesBefore = world.machines.length;
    click('[data-action="add-machine"]');
    check(world.machines.length === machinesBefore + 1 && document.querySelectorAll('[data-graph-machine]').length === world.machines.length, 'adding a machine rebuilds projection from same topology');
    click('[data-world-view="people"]');
    check(document.querySelectorAll('[data-machine]').length === world.machines.length, 'added machine exists in both views');
    check(document.documentElement.scrollWidth <= innerWidth, 'view fits viewport');
    sessionStorage.setItem('shared-view-test-expected', JSON.stringify({users: world.users.length, machines: world.machines.length, down: machine.id, time: world.time, request: request.id}));
    return {passed: results.length, results};
})()
