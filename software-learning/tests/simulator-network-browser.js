// Run with agent-browser eval --stdin on a fresh sd-book-14 architecture page.
(async () => {
    const results = [];
    const check = (ok, text) => { if (!ok) throw new Error(text); results.push(text); };
    const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
    const until = async (fn, message, ms = 5000) => {
        const end = Date.now() + ms;
        while (!fn() && Date.now() < end) await wait(30);
        check(!!fn(), message);
    };
    document.querySelector('.sim-start')?.click();
    const state = window.__simTestHooks.stateRef();
    state.operationOrigin = 'tw';
    const click = selector => document.querySelector(selector).dispatchEvent(new MouseEvent('click', { bubbles: true }));
    const key = () => document.querySelector('[data-drag-viewer]').dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    click('.sim-abr-stop');
    state.speed = .1;
    click('.sim-abr-origin');
    await until(() => state.abrFetchHandle?.circle && state.abr.fetching.sentMbit > 0, 'origin packet starts transmitting');
    const first = state.abrFetchHandle.circle;
    const firstId = state.abr.activeRequest.id;
    click('[data-instance="loadBalancer_tw::0"]');
    const x = first.getAttribute('cx'), y = first.getAttribute('cy');
    await until(() => first.classList.contains('lost'), 'closing fixed LB marks the SAME ball lost');
    check(first.isConnected && first.getAttribute('cx') === x && first.getAttribute('cy') === y, 'lost ball freezes at its interruption point');
    check(state.runtime.requests.find(r => r.id === firstId)?.status === 'failed', 'interrupted request is recorded as failed');
    check(state.abr.received === 1, 'partial packet is not counted as received');
    check(document.querySelector('.sim-trace-body').textContent.includes('斷線'), 'trace explicitly records disconnect');
    check(document.querySelector('[data-edge="users_tw-loadBalancer_tw"]').classList.contains('inactive'), 'failed node wires are inactive');
    await until(() => state.abr.servingRegion === 'us' && state.abr.fetching, 'US takes over the retry');
    check(state.abr.fetching.idx === 2 && state.abr.activeRequest.payload.attempt === 2, 'retry keeps the original segment number');
    check(state.dragViewer.regionId === 'tw', 'viewer stays in Taiwan');
    check(document.querySelector('[data-playback-route]').dataset.servingRegion === 'us', 'visible route matches US takeover');
    click('[data-instance="loadBalancer_tw::0"]');
    click('.sim-abr-stop');
    click('.sim-abr-origin');
    await until(() => state.abr.servingRegion === 'tw' && !!state.abrFetchHandle, 'healthy Taiwan route returns');
    const streamingBall = state.abrFetchHandle.circle;
    click('[data-instance="streamServer_tw::0"]');
    await until(() => streamingBall.classList.contains('lost'), 'ordinary Taiwan server click disconnects its active ball');
    check(!state.extraInstances.streamServer_tw && state.instanceDown['streamServer_tw::0'], 'clicking the server does not create replacement machines');
    await until(() => state.abr.servingRegion === 'us' && state.abr.fetching, 'Taiwan server failure retries through US server');
    click('[data-instance="streamServer_tw::0"]');
    click('[data-instance="transcodedStorage::0"]');
    await until(() => !!state.abr.failure, 'shared storage outage interrupts the replacement connection');
    const received = state.abr.received;
    await wait(1800);
    check(state.abr.received === received && !state.abr.fetching, 'no region bypasses a failed shared storage node');
    click('[data-instance="transcodedStorage::0"]');
    await until(() => !!state.abr.fetching, 'restoring storage resumes retries');
    click('.sim-abr-stop');
    click('.sim-abr-cdn');
    await until(() => state.abr.fetching && state.abr.fetching.sentMbit > 0, 'CDN transfer starts');
    const cdnBall = state.abrFetchHandle.circle;
    const sent = state.abr.fetching.sentMbit;
    key();
    check(state.dragViewer.inZone, 'keyboard/drag equivalent enters weak signal zone');
    check(document.querySelector('[data-abr-source-stat]').textContent.includes('0.4 Mbps'), 'CDN is capped by the weak last mile');
    await wait(180);
    check(state.abrFetchHandle.circle === cdnBall && state.abr.fetching.sentMbit > sent, 'weak signal slows the same transfer without replacing its ball');
    await until(() => state.abr.buffer === 0 && state.abr.stallActive, 'weak signal exhausts the buffer and stalls playback', 4000);
    key();
    check(!state.dragViewer.inZone, 'viewer leaves weak zone');
    await until(() => state.abr.received >= 2, 'the original transfer completes after signal recovery');
    check(!state.abr.stallActive, 'playback recovers from the same position');
    await until(() => !!state.abrFetchHandle, 'next CDN packet starts');
    const interrupted = state.abrFetchHandle.circle;
    click('[data-instance="cdn_tw::0"]');
    await until(() => interrupted.classList.contains('lost'), 'ordinary CDN click disconnects the active ball');
    await until(() => state.abr.deliveryMode === 'origin' && state.abr.fetching, 'CDN outage falls back to healthy origin');
    check(state.choice.cdnTier === 'all' && state.instanceDown['cdn_tw::0'], 'hardware failure preserves architecture strategy');
    click('[data-instance="apiServer_tw::0"]');
    check(document.querySelector('.sim-trace-body').textContent.includes('目前觀看路徑沒有經過'), 'unrelated API failure explains why playback is unaffected');
    const v = state.dragViewer;
    Object.assign(state.badZone, { x: v.x - 50, y: v.y - 50, width: 100, height: 100 });
    document.querySelector('[data-drag-zone]').dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
    check(v.inZone, 'moving the weak zone over the starting point affects the player');
    key();
    check(!v.inZone, 'keyboard can leave a weak zone that covers the original starting point');
    return { passed: results.length, results };
})()
