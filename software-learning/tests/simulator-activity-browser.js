(async () => {
    const results = [];
    const check = (ok, label) => { if (!ok) throw new Error(label); results.push(label); };
    const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
    const until = async (fn, label) => { for (let i = 0; i < 300 && !fn(); i++) await wait(50); check(fn(), label); };
    document.querySelector('.sim-start')?.click();
    const state = window.__simTestHooks.stateRef();
    const click = selector => document.querySelector(selector).dispatchEvent(new MouseEvent('click', { bubbles: true }));
    const tab = kind => click(`[data-activity-tab="${kind}"]`);
    const visible = kind => !document.querySelector(`[data-activity-panel="${kind}"]`).hidden;
    const submit = kind => document.querySelector(`[data-operation-form="${kind}"]`).requestSubmit();
    click('[data-speed="2"]');
    const playback = state.abr;
    const generation = state.abrGeneration;
    document.querySelector('[data-operation-form="upload"] input').value = '分頁測試影片 <b>保留文字</b>';
    click('[data-kind="upload"]');
    const upload = state.operationRequests.upload;
    check(visible('upload'), 'toolbar upload selects upload panel');
    tab('search'); tab('watch'); tab('upload');
    check(state.operationRequests.upload === upload, 'switching tabs preserves same upload request');
    check(state.abr === playback && state.abrGeneration === generation && state.abr.playing, 'switching tabs does not restart or stop playback');
    await until(() => upload.status === 'completed', 'upload completes while observed from another tab');
    check(upload.branches.every(b => b.done === b.total), 'progress reflects completed simulation packets');
    check(document.querySelector('[data-operation-result="upload"]').textContent.includes('影片已上架'), 'upload panel reports actual publish completion');
    document.querySelector('[data-operation-form="search"] input').value = '分頁測試影片';
    click('[data-kind="search"]');
    check(visible('search'), 'toolbar search selects query panel');
    const query = state.operationRequests.search;
    await until(() => query.status === 'completed', 'query completes through real request path');
    check(query.results.some(r => r.video_id === upload.payload.video_id), 'query returns the uploaded video from stored records');
    check(document.querySelector('.sim-search-results').textContent.includes('<b>保留文字</b>'), 'user title remains escaped text');
    check(query.payload.query === '分頁測試影片', 'request uses entered search condition');
    click('[data-instance="metadataCache::0"]');
    submit('search');
    const failed = state.operationRequests.search;
    await until(() => failed.status === 'failed', 'cache outage produces failed query');
    check(!document.querySelector('.sim-search-results'), 'failed query does not show stale successful results');
    check(document.querySelector('[data-operation-result="search"]').textContent.includes('路徑中斷'), 'query panel explains failure');
    click('[data-instance="metadataCache::0"]');
    submit('search');
    await until(() => state.operationRequests.search.status === 'completed', 'query succeeds after restoring cache');
    click('[data-instance="storage::0"]');
    click('[data-kind="upload"]');
    await until(() => state.operationRequests.upload.status === 'failed', 'storage outage fails upload');
    check(document.querySelector('[data-operation-result="upload"]').textContent.includes('未完成上架'), 'failed upload is not reported published');
    click('[data-instance="storage::0"]');
    tab('watch');
    check(visible('watch') && state.abr === playback, 'returning to watch keeps the original player');
    document.querySelector('[data-activity-tab="watch"]').dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
    check(visible('upload'), 'arrow keys switch accessible tabs');
    check(document.querySelectorAll('.sim-trace').length === 1, 'all tabs share a single log');
    check(document.documentElement.scrollWidth <= innerWidth, 'tabs fit viewport without page overflow');
    tab('search');
    document.querySelector('.sim-workbench').scrollIntoView();
    return { passed: results.length, results };
})()
