(()=>{
    const results=[];const check=(ok,label)=>{if(!ok)throw new Error(label);results.push(label);};
    const hook=window.__worldWorkbench,w=hook.world;
    const click=s=>document.querySelector(s).click();
    if(!hook.paused)click('[data-action="pause"]');
    Object.assign(w.options,{autoFaults:false,autoRepair:false,arrivals:false});
    click('[data-action="api-lab"]');
    check(!document.querySelector('#yw-api-controls').hidden,'API lab selects a real regional API');
    click('[data-action="configure-api"]');
    const api=w.machines.find(m=>m.kind==='api'&&m.region==='tw');
    check(api.slots===2&&api.capacity===2&&api.queueTimeout===2,'capacity form configures actual model');
    const users=w.users.length;
    const existing=new Set(w.requests.map(r=>r.id));
    click('[data-action="burst-api"]');
    const batch=w.requests.filter(r=>r.loadTest&&!existing.has(r.id));
    check(batch.length===10&&new Set(batch.map(r=>r.id)).size===10,'ten clicks worth of independent requests are created');
    click('[data-action="step"]');
    check(batch.filter(r=>r.status==='running').length===2&&batch.filter(r=>r.status==='queued').length===8,'two working and eight queued are visible');
    check(document.querySelector('#yw-api-results').textContent.includes('8 排隊'),'UI reports real queue');
    for(let i=0;i<22;i++)click('[data-action="step"]');
    check(batch.some(r=>r.retries>0),'real simulation time produces queue timeout failures');
    const failed=batch.find(r=>r.retries>0);
    click(`[data-request="${failed.id}"]`);
    check(!document.querySelector('[data-inspector-pane="request"]').hidden,'request selection opens adjacent inspector');
    check(document.querySelector('#yw-request-detail').textContent.includes('容量滿'),'selected request explains its failure');
    click(`[data-machine="${api.id}"]`);
    document.querySelector('#yw-api-slots').value=16;document.querySelector('#yw-api-rate').value=32;document.querySelector('#yw-api-timeout').value=12;
    click('[data-action="configure-api"]');
    w.step(12);hook.paint();
    check(batch.every(r=>r.status==='completed'),'increasing capacity completes same queued/retrying batch');
    check(w.users.length===users,'stress clients do not replace or add viewer sessions');
    check(getComputedStyle(document.querySelector('.yw-toolbar')).top==='0px','toolbar stays at viewport top');
    check(!document.querySelector('.yw-advanced').open,'large architecture settings are collapsed');
    check(getComputedStyle(document.querySelector('.youtube-mode-nav')).position==='static','mode navigation no longer overlaps sticky toolbar');
    check(document.querySelector('.yw-ledger').getBoundingClientRect().top>=document.querySelector('.yw-workspace').getBoundingClientRect().bottom,'request log follows the map and inspector');
    const divider=document.querySelector('.yw-resize-y'),height=document.querySelector('.yw-table-wrap').offsetHeight;
    divider.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}));
    check(document.querySelector('.yw-table-wrap').offsetHeight===height+24,'LOG height is adjustable');
    check(document.documentElement.scrollWidth<=innerWidth,'workspace fits viewport');
    return{passed:results.length,results};
})()
