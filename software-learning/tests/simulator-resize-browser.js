(async () => {
    const results = [];
    const check = (ok, label) => { if (!ok) throw new Error(label); results.push(label); };
    document.querySelector('.sim-start')?.click();
    document.querySelector('.sim-abr-stop').click();
    const reset = document.querySelector('.sim-layout-controls button');
    reset.click();
    const columns = document.querySelector('[data-resize="columns"]');
    const rows = document.querySelector('[data-resize="rows"]');
    const side = document.querySelector('.sim-workbench-side');
    const activity = document.querySelector('.sim-activity');
    const log = document.querySelector('.sim-trace-body');
    check(activity.offsetWidth === side.clientWidth, 'activity fills side panel at every viewport');
    check(document.querySelector('.sim-trace').offsetWidth === side.clientWidth, 'log fills side panel at every viewport');
    const narrow = innerWidth <= 1000;
    const target = narrow ? document.querySelector('.sim-topo-scroll') : side;
    const measure = () => narrow ? target.offsetHeight : target.offsetWidth;
    const key = (el, value) => el.dispatchEvent(new KeyboardEvent('keydown', { key: value, bubbles: true }));
    check(columns.getAttribute('aria-orientation') === (narrow ? 'horizontal' : 'vertical'), 'divider orientation matches viewport');
    const before = measure();
    key(columns, narrow ? 'ArrowDown' : 'ArrowLeft');
    check(measure() > before, 'keyboard enlarges map height or side width');
    key(columns, 'End');
    check(document.documentElement.scrollWidth <= innerWidth, 'maximum pane size never overflows page');
    key(columns, 'Home');
    check(measure() > 200, 'minimum pane size remains usable');
    reset.click();
    const oldHeight = activity.offsetHeight, oldLog = log.offsetHeight;
    key(rows, 'ArrowDown');
    check(activity.offsetHeight === oldHeight + 24, 'row divider increases activity height');
    check(log.offsetHeight === oldLog - 24, 'row divider gives corresponding space back from log');
    check(JSON.parse(localStorage.getItem('youtube-workbench-layout-v1')).activity === oldHeight + 24, 'layout preference persists');
    document.querySelector('[data-activity-tab="upload"]').click();
    check(activity.offsetHeight === oldHeight + 24, 'switching activity preserves pane proportions');
    const zoom = document.querySelector('[data-map-zoom]');
    check(zoom.value === 'fit' && document.querySelector('.sim-topo').getBoundingClientRect().width <= document.querySelector('.sim-topo-scroll').clientWidth + 1, 'fit mode keeps entire map width in pane');
    reset.click();
    check(activity.offsetHeight === 560, 'reset restores default activity height');
    check(document.documentElement.scrollWidth <= innerWidth, 'no page horizontal overflow');
    return { passed: results.length, results };
})()
